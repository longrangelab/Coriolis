#!/usr/bin/env python3
"""Build lib/WebUI/LearnJs.h from web/learn/ (index.html + wind-learner.js).

The page in web/learn/ is the source. It is also published as a standalone
simulator page, where the host wraps it in <html>/<head> and Google Fonts load.
On the base station there is no internet, so this script:
  * wraps the page in its own <!doctype html> head (charset, viewport),
  * drops the Google Fonts links (the font stacks fall back to system fonts),
  * adds a "Wind Lab" back link where the page has <!--BACKLINK-->.
Run it after editing anything in web/learn/; CI fails if LearnJs.h is stale.
"""
import hashlib, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent
out = here.parent.parent / 'lib' / 'WebUI' / 'LearnJs.h'

page = (here / 'index.html').read_text(encoding='utf-8')
lib = (here / 'wind-learner.js').read_text(encoding='utf-8')

# the page knows which build it is; the base sends the build it serves with
# every /windsec reply, so a page left open across a reflash reloads itself
build = hashlib.sha1((page + lib).encode('utf-8')).hexdigest()[:10]
page = page.replace('__LEARN_BUILD__', build)
lib = lib.replace('__LEARN_BUILD__', build)

page = re.sub(r'<link rel="(?:preconnect|stylesheet)" href="https://fonts\.[^"]*"[^>]*>\n?', '', page)
page = page.replace('<!--BACKLINK-->',
    '<a href="/" class="btn" style="text-decoration:none;color:inherit" '
    'onclick="try{localStorage.setItem(\'section\',\'basic\')}catch(e){}">&larr; Wind Lab</a>')
head = ('<!doctype html>\n<html lang="en"><head><meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n')
# the page starts with <title>/<meta>/<style>; close head before the first header
page = head + page.replace('<header class="top">', '</head><body>\n<header class="top">', 1) + '\n</body></html>\n'

for name, text, delim in (('LEARN_HTML', page, 'LEARNHTML'), ('LEARN_LIB_JS', lib, 'LEARNLIB')):
    if (')' + delim + '"') in text:
        sys.exit('delimiter clash in ' + name)

h = ('// LearnJs.h -- GENERATED by web/learn/build_learn_h.py. Do not edit by hand.\n'
     '//\n'
     '// /learn            the Wind Learning Range page: Practice (simulated field)\n'
     '//                   and Live (reads /data.json + /windsec from this base),\n'
     '//                   SHOT, dial entry, shot plotting, meter relationships,\n'
     '//                   saved models/sessions, and the model Wind Lab runs live\n'
     '// /wind-learner.js  the learner itself (geometry, physics weights, Kalman\n'
     '//                   update, lagged meter relationships, live model export)\n'
     '#pragma once\n#include <Arduino.h>\n\n'
     '#define LEARN_BUILD "' + build + '"   // sent as X-Learn-Build on /windsec\n\n'
     'static const char LEARN_HTML[] PROGMEM = R"LEARNHTML(' + page + ')LEARNHTML";\n\n'
     'static const char LEARN_LIB_JS[] PROGMEM = R"LEARNLIB(' + lib + ')LEARNLIB";\n')

if '--check' in sys.argv:
    cur = out.read_text(encoding='utf-8') if out.exists() else ''
    if cur != h:
        sys.exit('LearnJs.h is stale: run python3 "Coriolis/User Side/web/learn/build_learn_h.py"')
    print('LearnJs.h is up to date')
else:
    out.write_text(h, encoding='utf-8')
    print('wrote', out, len(h), 'bytes')
